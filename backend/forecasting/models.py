from django.db import models


class MonthlyPriceRecord(models.Model):
    """
    Stores historical monthly price data.
    The date is standardized to the 1st of each month (YYYY-MM-01).
    """
    date = models.DateField(
        unique=True,
        db_index=True,
        help_text="Standardized monthly date (YYYY-MM-01)"
    )
    price = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        help_text="Historical monthly price"
    )
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['date']
        verbose_name = 'Monthly Price Record'
        verbose_name_plural = 'Monthly Price Records'

    def __str__(self):
        return f"{self.date.strftime('%Y-%m')}: {self.price}"


class ModelMetadata(models.Model):
    """
    Stores metadata, training parameters, and statistical evaluation metrics
    for the trained SARIMA model.
    """
    name = models.CharField(max_length=100, default="SARIMA(0,1,2)(0,0,1,12)")
    order_p = models.IntegerField(default=0)
    order_d = models.IntegerField(default=1)
    order_q = models.IntegerField(default=2)
    seasonal_p = models.IntegerField(default=0)
    seasonal_d = models.IntegerField(default=0)
    seasonal_q = models.IntegerField(default=1)
    seasonal_s = models.IntegerField(default=12)
    
    # Information criteria from model fit
    aic = models.FloatField(null=True, blank=True, help_text="Akaike Information Criterion")
    bic = models.FloatField(null=True, blank=True, help_text="Bayesian Information Criterion")
    hqic = models.FloatField(null=True, blank=True, help_text="Hannan-Quinn Information Criterion")
    
    # Evaluation error metrics
    mae = models.FloatField(null=True, blank=True, help_text="Mean Absolute Error")
    rmse = models.FloatField(null=True, blank=True, help_text="Root Mean Squared Error")
    mape = models.FloatField(null=True, blank=True, help_text="Mean Absolute Percentage Error (%)")
    
    training_sample_count = models.IntegerField(default=0)
    data_start_date = models.DateField(null=True, blank=True)
    data_end_date = models.DateField(null=True, blank=True)
    trained_at = models.DateTimeField(auto_now=True)
    is_active = models.BooleanField(default=True)

    class Meta:
        ordering = ['-trained_at']
        verbose_name = 'Model Metadata'
        verbose_name_plural = 'Model Metadata'

    def __str__(self):
        return f"{self.name} (trained at {self.trained_at.strftime('%Y-%m-%d %H:%M')})"


class ForecastCache(models.Model):
    """
    Persisted 12-month forecast output generated by the SARIMA model.
    """
    forecast_date = models.DateField(
        unique=True,
        db_index=True,
        help_text="Standardized forecast date (YYYY-MM-01)"
    )
    predicted_price = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        help_text="Predicted point estimate price"
    )
    confidence_lower = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        help_text="Lower bound of 95% confidence interval"
    )
    confidence_upper = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        help_text="Upper bound of 95% confidence interval"
    )
    confidence_level = models.FloatField(default=0.95)
    created_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ['forecast_date']
        verbose_name = 'Forecast Cache'
        verbose_name_plural = 'Forecast Caches'

    def __str__(self):
        return f"{self.forecast_date.strftime('%Y-%m')}: {self.predicted_price} [{self.confidence_lower} - {self.confidence_upper}]"
